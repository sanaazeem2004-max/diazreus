// Generates src/data/{offices,map,attorneys}.generated.js from the audited source data.
// Run: node scripts/build-data.mjs
import fs from 'fs';
import { geoNaturalEarth1, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';
import { OFFICES, REGIONS } from './offices.source.js';

const slugify = s => s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const header = '// AUTO-GENERATED by scripts/build-data.mjs — do not edit by hand.\n';

/* ---------- Map ---------- */
const W = 1000;
const world = JSON.parse(fs.readFileSync('node_modules/world-atlas/land-110m.json', 'utf8'));
const land = feature(world, world.objects.land);
// Fit the whole sphere to the width, then crop the viewBox to 84°N…58°S (drops Antarctica).
const projection = geoNaturalEarth1().rotate([-10, 0]).fitWidth(W, { type: 'Sphere' });
const pathGen = geoPath(projection);
const Y0 = Math.round(projection([0, 84])[1]);
const H = Math.round(projection([0, -58])[1]) - Y0;
const landPath = pathGen(land).replace(/(\d+\.\d)\d+/g, '$1');

const offices = OFFICES.map(o => {
  const [x, y] = projection([o.lng, o.lat]);
  return {
    ...o,
    slug: slugify(o.city),
    x: +x.toFixed(1),
    y: +y.toFixed(1),
    mapsUrl: 'https://www.google.com/maps/search/?api=1&query=' + encodeURIComponent(o.address.includes(o.city) ? `${o.address}, ${o.country}` : `${o.address}, ${o.city}, ${o.country}`),
  };
});

fs.writeFileSync('src/data/map.generated.js', `${header}export const MAP_W = ${W};\nexport const MAP_H = ${H};
export const MAP_Y0 = ${Y0};\nexport const LAND_PATH = ${JSON.stringify(landPath)};\n`);
fs.writeFileSync('src/data/offices.generated.js', `${header}export const REGIONS = ${JSON.stringify(REGIONS)};\nexport const OFFICES = ${JSON.stringify(offices, null, 1)};\n`);

/* ---------- Attorneys ---------- */
const profiles = JSON.parse(fs.readFileSync('audit/profiles.json', 'utf8'));
const OFFICE_RULES = [
  [/Miami Tower|Miami, Florida|S\.E\. 2nd Street/i, 'miami'], [/Connecticut Avenue/i, 'washington-d-c'], [/Garden City|New York/i, 'new-york'],
  [/Wilshire/i, 'los-angeles'], [/Post Oak|Houston/i, 'houston'], [/Yonge|Toronto/i, 'toronto'],
  [/Lahore/i, 'lahore'], [/Saudi Arabia|Riyadh/i, 'riyadh'], [/Abu Dhabi|ADIB/i, 'abu-dhabi'], [/Prague/i, 'prague'],
  [/Frankfurt/i, 'frankfurt'], [/Athens/i, 'athens'], [/Moscow/i, 'moscow'], [/Oranjestad|Aruba/i, 'oranjestad'],
  [/Buenos Aires/i, 'buenos-aires'], [/Berrini/i, 'sao-paulo'], [/Santiago|Santa Lucia/i, 'santiago'],
  [/Carrera|Bogot|Cra\. 13/i, 'bogota'], [/Piantini|Santo Domingo/i, 'santo-domingo'], [/Bosque de Duraznos/i, 'mexico-city'],
  [/Icasa|Obarrio/i, 'panama-city'], [/República de Panamá|San Isidro/i, 'lima'], [/Altamira|Caracas/i, 'caracas'],
];
const PRACTICE_RULES = {
  'international-litigation-arbitration': /litigat|arbitra/i,
  'white-collar-crime-government-sanctions': /white[- ]collar|sanction|OFAC|criminal defen[cs]e|prosecut/i,
  'international-fraud-and-asset-recovery': /fraud|asset recovery|asset[- ]tracing/i,
  'regulatory-and-corporate-investigations-governance-and-compliance': /compliance|regulator|corporate investigation|anti-money|\bAML\b|governance/i,
  'corporate-ma': /merger|\bM&A\b|acquisition/i,
  'corporate-business-transactions-international-trade': /international trade|business transaction|commercial transaction|cross-border transaction|export/i,
  'blockchain-and-cryptocurrency': /crypto|blockchain|digital asset/i,
  'drrt': /DRRT|securities litigation|institutional investor/i,
  'estate-and-tax-planning': /estate planning|trusts? and estates|tax/i,
  'athlete-representation-and-entertainment-law': /athlete|entertain|sports/i,
  'intellectual-property': /intellectual property|trademark|patent|copyright/i,
  'cuba-practice': /\bCuba/i,
  'bankruptcy-and-asset-recovery': /bankrupt|insolven|creditor|liquidat/i,
  'real-estate': /real estate/i,
  'family-law': /family law|divorce|custody|matrimonial/i,
  'immigration-for-businesses-and-individuals': /immigra|visa|EB-5|naturaliz/i,
};
const officeBySlug = Object.fromEntries(offices.map(o => [o.slug, o]));
const seen = new Set();
const people = [];
for (const p of profiles) {
  const slug = slugify(p.name);
  if (seen.has(slug)) continue;
  seen.add(slug);
  const rule = OFFICE_RULES.find(([re]) => re.test(p.address || ''));
  const office = rule ? officeBySlug[rule[1]] : null;
  const bio = (p.bio || []).map(s => s.replace(/\s+/g, ' ').trim());
  const bioText = bio.join(' ') + ' ' + p.title;
  const practices = Object.entries(PRACTICE_RULES).filter(([, re]) => re.test(bioText)).map(([k]) => k);
  const isInvestigator = p.regions.includes('Investigators') || /Investigator/i.test(p.title);
  people.push({
    slug,
    name: p.name.replace(/\s+/g, ' ').trim(),
    title: p.title || (isInvestigator ? 'Investigator' : 'Attorney'),
    type: isInvestigator ? 'investigator' : 'attorney',
    office: office?.slug ?? null,
    officeLabel: office ? `${office.city}${office.country.includes('USA') ? '' : ', ' + office.country}` : null,
    region: office?.region ?? null,
    email: p.email || null,
    phone: p.phone ? p.phone.replace(/\s+/g, ' ') : null,
    linkedin: p.linkedin || null,
    photo: p.photo,
    profileUrl: p.link,
    bio,
    quotes: (p.quotes || []).filter(q => q.q.length > 30),
    practices,
  });
}
const ORDER = ['Global Managing Partner', 'Administrative Managing Partner', 'Founding Partner', 'Partner', 'Senior Counsel', 'Senior Tax Attorney', 'Senior Trusts & Estates Attorney', 'Of Counsel', 'Local Partner', 'Foreign Legal Consultant', 'Associate Attorney'];
const rank = t => { const i = ORDER.indexOf(t); return i === -1 ? 50 : i; };
people.sort((a, b) => rank(a.title) - rank(b.title) || a.name.localeCompare(b.name));
fs.writeFileSync('src/data/people.generated.js', `${header}export const PEOPLE = ${JSON.stringify(people, null, 1)};\n`);

const missing = people.filter(p => !p.office).map(p => p.name);
console.log(`offices: ${offices.length}, people: ${people.length}, no office: ${missing.join(', ') || 'none'}`);
console.log('practice coverage:', Object.keys(PRACTICE_RULES).map(k => `${k.split('-')[0]}:${people.filter(p => p.practices.includes(k)).length}`).join(' '));
